# -*- coding: utf-8 -*-
"""合规拒答策略（设计基线：命中即不调用模型，直接返回标准拒答）。

依据需求合规 D4 / 接口设计 §3.5。仅做关键词粗筛，命中后由前端展示标准话术，
绝不进入 LLM，避免生成用药/诊断等高风险内容。

2026-09-11 调整：孕婴类不再一刀切——"孕妇能吃山楂吗"这类一般性饮食常识问题
放行（知识库有"慎用+咨询医师"的标准口径），仅当孕婴词与医疗干预词同时出现
（如"孕妇感冒吃什么药"）才拒答。

2026-10-16 调整（两处，均由用例 IT-C-08/09/10 实测暴露）：
  ① 诊断与报告解读的触发词过窄："我是不是糖尿病""帮我解读下指标"都漏过了关键词表；
     补口语化正则 + 检验类词。"是不是糖尿病"要拒，但**裸病名要放行**——
     本平台核心场景就是慢病食养，"糖尿病主食怎么选"必须正常回答。
  ② 孕婴类**恢复整类拒答**：2026-09-11 曾自行收窄为"孕婴词 + 医疗干预词同现才拒"，
     但需求 V1.3 D4 与需求评审 D4 明确把"孕妇及婴幼儿特殊人群"整列进拒答清单，
     用例 IT-C-10（P0）亦要求拒答。收窄属实现侧自定口径，与需求不符，故回退为整类拒答
     并统一引导就医（孕产/婴幼儿营养请由产科或儿科医师评估）。
"""
import re
from typing import Tuple

# 各拒答类别触发词（可后续接入 system_config 配置化）
_REFUSE_RULES = {
    "medical_advice": ["吃多少粒", "剂量", "用量", "开药", "处方", "停药", "换药",
                       "怎么吃药", "吃什么药", "怎么停", "能否停"],
    "diagnosis": ["确诊", "是不是得了", "诊断", "是什么病", "严重吗", "会不会恶化",
                  "算不算病", "有没有问题"],
    "report_interpretation": ["报告单", "化验单", "检查报告", "帮我看下报告", "体检报告",
                              "化验", "检验单", "血常规", "尿常规", "肝功", "肾功",
                              "转氨酶", "肌酐", "影像", "超声", "CT片",
                              "核磁", "胃镜", "肠镜", "病理"],
}

# 诊断询问的口语说法："我是不是糖尿病""会不会是痛风"
# 注意：**不把裸病名（糖尿病/高血压）列入拒答**——本平台核心场景就是慢病食养
# （"糖尿病主食怎么选"必须放行），拒的只是"帮我判断我有没有得病"这类诊断诉求。
_DIAGNOSIS_PATTERNS = [
    re.compile(r"(是不是|是否|会不会|算不算|有没有)[^，。！？?!,.]{0,6}"
               r"(得|患|有)?[^，。！？?!,.]{0,2}"
               r"(病|癌|症|糖尿病|高血压|高血脂|痛风|脂肪肝|贫血|结节)"),
]

# 报告解读的口语说法："帮我解读一下指标"
_REPORT_PATTERNS = [
    re.compile(r"(帮我|请|麻烦)?[^，。！？?!,.]{0,4}(看看|解读|分析|判断|读一下)[^，。！？?!,.]{0,6}"
               r"(报告|化验|检验|指标|数值|结果|这单|这张)"),
]

# 剂量询问的正则兜底（关键词表覆盖不到的口语说法）
# 例："我该吃多少降压药" / "一天吃几粒" / "胰岛素打多少个单位" / "这个药服用多少毫克"
_MED_DOSE_PATTERNS = [
    re.compile(r"(吃|服|用|喝|注射|打)[^，。！？?!,.]{0,4}(多少|几)[^，。！？?!,.]{0,3}"
               r"(药|片|粒|颗|勺|毫升|ml|ML|mg|毫克|克|单位|支|管)"),
    re.compile(r"(药|片|粒|颗|针|胰岛素)[^，。！？?!,.]{0,4}(吃|服|用|打)[^，。！？?!,.]{0,4}(多少|几)"),
]

# 常见处方药 / 医疗干预名：出现即属医疗建议范畴
_MED_DRUG_WORDS = ["降压药", "降糖药", "降脂药", "安眠药", "抗生素", "止痛药", "退烧药",
                   "消炎药", "靶向药", "化疗", "放疗", "激素药", "免疫抑制剂",
                   "输液", "打针", "静脉注射"]

# 孕婴特殊人群：整类拒答（需求 V1.3 D4 / 需求评审 D4 / 用例 IT-C-10）
_PREG_KEYWORDS = ["孕妇", "怀孕", "孕期", "哺乳期", "哺乳", "妊娠", "产妇", "坐月子",
                  "婴幼儿", "婴儿", "新生儿", "胎儿", "宝宝", "备孕"]
# 注意：不能用裸"药"字——山药、药膳、芍药等食药同源名称含"药"会误伤
_REFUSAL_REASON_TEXT = {
    "medical_advice": "用药与剂量建议",
    "diagnosis": "疾病诊断",
    "report_interpretation": "检查报告解读",
    "pregnancy": "孕产妇与婴幼儿特殊人群",
}


def check_refusal(text: str) -> Tuple[bool, str]:
    """返回 (是否拒答, 拒答原因)。

    优先级：用药 > 诊断 > 报告解读 > 孕婴特殊人群。
    """
    if not text:
        return False, ""
    t = text.lower()
    for reason, keywords in _REFUSE_RULES.items():
        for kw in keywords:
            if kw.lower() in t:
                return True, reason
    # 口语化表达的正则兜底（关键词表难以穷举说法）
    for pat in _DIAGNOSIS_PATTERNS:
        if pat.search(t):
            return True, "diagnosis"
    for pat in _REPORT_PATTERNS:
        if pat.search(t):
            return True, "report_interpretation"
    for pat in _MED_DOSE_PATTERNS:
        if pat.search(t):
            return True, "medical_advice"
    if any(w in t for w in _MED_DRUG_WORDS):
        return True, "medical_advice"
    # 孕婴：整类拒答，不再要求同时出现医疗干预词
    if any(k in t for k in _PREG_KEYWORDS):
        return True, "pregnancy"
    return False, ""


def refusal_message(reason: str) -> str:
    """标准化拒答话术：说明拒答类别 + 引导正规医疗渠道（合规 D4）。"""
    kind = _REFUSAL_REASON_TEXT.get(reason, "该类问题")
    if reason == "pregnancy":
        return (f"涉及{kind}的营养问题，我无法给出建议，请由产科或儿科医师评估。"
                "我可以帮你梳理一般性的食材性味与饮食结构常识，具体摄入请遵医嘱。")
    return (f"该问题涉及{kind}，我无法回答，建议咨询医生或前往正规医疗机构就诊。"
            "我擅长药食同源食材、慢病饮食原则等一般性饮食常识，可以换个问法。")
