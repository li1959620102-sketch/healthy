def normalize(label: Label) -> Tuple[str, List[str]]:
    """把标注统一成 (mode, expected_intents)。

    mode ∈ {"normal", "multi", "blocked", "fallback"}
    """
    if isinstance(label, str):
        return label, []
    return ("multi" if len(label) > 1 else "normal"), list(label)


